/**
 * UGC Carousels & Shoppable Videos for WooCommerce — Admin JavaScript
 */
/* global ugccAdmin, wp */
jQuery(function ($) {

    /**
     * Handle config form submission via AJAX.
     *
     * @param {jQuery.Event} submitEvent - The form submit event.
     * @return {void}
     */
    function onConfigFormSubmit( submitEvent ) {
        submitEvent.preventDefault();
        var $form   = $(this);
        var $status = $form.find('.ugcc-save-status');

        $.post(ugccAdmin.ajaxurl, {
            action:      $form.data('action'),
            nonce:       ugccAdmin.nonce,
            carousel_id: $form.find('[name="carousel_id"]').val(),
            name:        $form.find('[name="name"]').val(),
            mute:          $form.find('[name="mute"]:checked').val(),
            direction:     $form.find('[name="direction"]:checked').val(),
            hide_atc:      $form.find('[name="hide_atc"]:checked').val(),
            show_products: $form.find('[name="show_products"]:checked').val(),
        })
        .done(function (res) {
            $status.text((res.data && res.data.message) ? res.data.message : 'Saved!')
                   .css('color', 'green');
        })
        .fail(function () {
            $status.text('Error saving.').css('color', 'red');
        })
        .always(function () {
            setTimeout(function () { $status.text(''); }, 3000);
        });
    }
    $('#ugcc-config-form').on('submit', onConfigFormSubmit);

    $('#ugcc-items-list').sortable({
        handle:      '.ugcc-drag-handle',
        axis:        'y',
        placeholder: 'ugcc-sortable-placeholder',
    });

    $('#ugcc-add-blank-row').on('click', function () {
        var newItemRowId = 'new-' + Date.now();
        var $row         = $(ugccBuildItemRow(newItemRowId));
        $('#ugcc-items-list').append($row);
    });

    /**
     * Handle media picker button click — opens WP media modal for image or video.
     *
     * @param {jQuery.Event} clickEvent - The button click event.
     * @return {void}
     */
    function onMediaBtnClick( clickEvent ) {
        clickEvent.preventDefault();
        var $btn      = $(this);
        var $input    = $btn.siblings('.ugcc-url-input');
        var mediaType = ($btn.data('media-type') || 'video').toString();
        var isImage   = mediaType === 'image';

        var mediaFrame = wp.media({
            title:    isImage ? (ugccAdmin.imageTitle  || 'Select Image') : (ugccAdmin.mediaTitle  || 'Select Video'),
            button:   { text: isImage ? (ugccAdmin.imageButton || 'Use this image') : (ugccAdmin.mediaButton || 'Use this video') },
            library:  { type: isImage ? 'image' : 'video' },
            multiple: false,
        });

        mediaFrame.on('select', function () {
            var attachment = mediaFrame.state().get('selection').first().toJSON();
            $input.val(attachment.url);
        });

        mediaFrame.open();
    }
    $(document).on('click', '.ugcc-media-btn', onMediaBtnClick);

    /**
     * Build HTML for a new (unsaved) item row with Dual Resolutions.
     * Uses the native HTML script template generated by content-tab.php.
     *
     * @param {string} rowId - Unique row identifier (prefixed "new-<timestamp>" for unsaved rows).
     * @return {string} HTML string for the new row.
     */
    function ugccBuildItemRow( rowId ) {
        var tmpl = $('#tmpl-ugcc-item-row').html();
        return tmpl.replace(/\{\{rowId\}\}/g, rowId);
    }

    /**
     * Build an HTML suggestion item for a single WooCommerce product.
     *
     * @param {Object}       product                    - Product data from the AJAX response.
     * @param {number}       product.id                 - WooCommerce product ID.
     * @param {string}       product.name               - Product name (unescaped).
     * @param {string}       product.sku                - Product SKU.
     * @param {string}       product.price_html         - Sanitized plain-text price (wp_strip_all_tags on server).
     * @param {string|false} product.thumbnail          - Thumbnail URL or false if none.
     * @param {string}       product.status             - Post status (publish, draft, private, etc.).
     * @param {string}       product.catalog_visibility - Catalog visibility setting.
     * @return {string} HTML string to append to the suggestions list.
     */
    function ugccBuildProductSuggestionHtml( product ) {
        // Use the DOM API to set src so the browser enforces safe URL handling,
        // preventing src-based XSS from unexpected server responses.
        var thumbnailHtml;
        if ( product.thumbnail ) {
            var thumbImg  = document.createElement('img');
            thumbImg.src  = product.thumbnail;
            thumbImg.alt  = '';
            thumbnailHtml = thumbImg.outerHTML;
        } else {
            thumbnailHtml = '<span class="ugcc-no-thumb"></span>';
        }

        var cleanName = $('<div>').text(product.name).html();

        var skuHtml = product.sku
            ? 'SKU: ' + $('<div>').text(product.sku).html()
            : '';

        var statusBadge = '';
        if (product.status && product.status !== 'publish') {
            var statusLabel = product.status.charAt(0).toUpperCase() + product.status.slice(1);
            statusBadge = '<span class="ugcc-badge ugcc-badge--' + product.status + '">' + statusLabel + '</span>';
        }

        var visibilityBadge = '';
        if (product.catalog_visibility === 'hidden') {
            visibilityBadge = '<span class="ugcc-badge ugcc-badge--hidden">Hidden from catalog</span>';
        } else if (product.catalog_visibility === 'search') {
            visibilityBadge = '<span class="ugcc-badge ugcc-badge--visibility">Search only</span>';
        } else if (product.catalog_visibility === 'catalog') {
            visibilityBadge = '<span class="ugcc-badge ugcc-badge--visibility">Catalog only</span>';
        }

        // price_html is server-sanitized via wp_strip_all_tags() in ProductSearch.php — plain text only.
        return $('#tmpl-ugcc-product-suggestion').html()
            .replace(/\{\{productId\}\}/g,      product.id)
            .replace(/\{\{productNameRaw\}\}/g,  cleanName)
            .replace(/\{\{thumbHtml\}\}/g,       thumbnailHtml)
            .replace(/\{\{productNameTxt\}\}/g,  cleanName)
            .replace(/\{\{productPrice\}\}/g,    product.price_html)
            .replace(/\{\{skuHtml\}\}/g,         skuHtml)
            .replace(/\{\{statusBadge\}\}/g,     statusBadge)
            .replace(/\{\{visibilityBadge\}\}/g, visibilityBadge);
    }

    var searchTimers = {};

    /**
     * Handle product search input — debounced AJAX lookup, renders suggestion list.
     *
     * @return {void}
     */
    function onProductSearchKeyup() {
        var $input       = $(this);
        var rowId        = $input.data('row');
        var term         = $input.val();
        var $suggestions = $input.siblings('.ugcc-product-suggestions');

        clearTimeout(searchTimers[rowId]);

        if (term.length < 2) {
            $suggestions.hide().empty();
            return;
        }

        searchTimers[rowId] = setTimeout(function () {
            $.get(ugccAdmin.ajaxurl, {
                action: 'ugcc_product_search',
                nonce:  ugccAdmin.nonce,
                term:   term,
            })
            .done(function (res) {
                $suggestions.empty();
                if (!res.success || !res.data.length) {
                    $suggestions.hide();
                    return;
                }
                $.each(res.data, function (i, product) {
                    $suggestions.append(ugccBuildProductSuggestionHtml(product));
                });
                $suggestions.show();
            });
        }, 300);
    }
    $(document).on('keyup', '.ugcc-product-search', onProductSearchKeyup);

    // Click outside → close suggestions.
    $(document).on('click', function (e) {
        if (!$(e.target).closest('.ugcc-product-search-wrap').length) {
            $('.ugcc-product-suggestions').hide();
        }
    });

    /**
     * Handle product suggestion click — add selected product as a chip.
     *
     * @return {void}
     */
    function onProductSuggestionClick() {
        var $li           = $(this);
        var productId     = $li.data('id');
        var productName   = $li.data('name');
        var $wrap         = $li.closest('.ugcc-product-search-wrap');
        var rowId         = $wrap.siblings('.ugcc-product-search-wrap').find('.ugcc-product-search').data('row') ||
                            $li.closest('.ugcc-item-row').data('id');
        var $selectedList = $li.closest('.ugcc-item-products').find('.ugcc-selected-products');

        // Avoid duplicates.
        if ($selectedList.find('[value="' + productId + '"]').length) {
            $li.closest('.ugcc-product-suggestions').hide().empty();
            return;
        }

        var tmpl = $('#tmpl-ugcc-product-chip').html();
        tmpl = tmpl.replace(/\{\{productId\}\}/g,   productId)
                   .replace(/\{\{productName\}\}/g,  productName)
                   .replace(/\{\{rowId\}\}/g,        rowId);

        $selectedList.append(tmpl);
        $li.closest('.ugcc-product-suggestions').hide().empty();
        $li.closest('.ugcc-item-products').find('.ugcc-product-search').val('');
    }
    $(document).on('click', '.ugcc-product-suggestions li', onProductSuggestionClick);

    $(document).on('click', '.ugcc-remove-product', function () {
        $(this).closest('li.ugcc-chip').remove();
    });

    /**
     * Handle item row delete button click — removes from DOM; calls AJAX for persisted rows.
     *
     * @return {void}
     */
    function onDeleteItemClick() {
        var $btn  = $(this);
        var rowId = $btn.data('id');
        var $row  = $btn.closest('.ugcc-item-row');

        // Persisted DB row (numeric id) → call AJAX delete endpoint then remove.
        if (!isNaN(parseInt(rowId, 10))) {
            $.post(ugccAdmin.ajaxurl, {
                action: 'ugcc_delete_item',
                nonce:  ugccAdmin.nonce,
                id:     rowId,
            })
            .always(function () {
                $row.fadeOut(200, function () { $(this).remove(); });
            });
        } else {
            // Newly-added row not yet in DB — just remove from DOM.
            $row.fadeOut(200, function () { $(this).remove(); });
        }
    }
    $(document).on('click', '.ugcc-delete-item', onDeleteItemClick);

    /**
     * Collect carousel item data from the DOM for the save-content AJAX call.
     *
     * @return {Object} Map of index → item data objects ready for the server.
     */
    function ugccCollectContentItems() {
        var items = {};

        $('#ugcc-items-list .ugcc-item-row').each(function (index) {
            var $row       = $(this);
            var rowId      = $row.data('id');
            var videoId    = $row.find('[name="items[' + rowId + '][video_id]"]').val() || 0;
            var videoUrlHd = $row.find('[name="items[' + rowId + '][video_url_hd]"]').val();
            var videoUrlSd = $row.find('[name="items[' + rowId + '][video_url_sd]"]').val();
            var posterUrl  = $row.find('[name="items[' + rowId + '][poster_url]"]').val();
            var products   = {};

            $row.find('.ugcc-chip').each(function () {
                var $chip      = $(this);
                var productId  = $chip.find('input[type="hidden"][name$="[id]"]').val();
                // 3-state select: '' = inherit global, '0' = force show, '1' = force hide.
                var hideAtcRaw = $chip.find('select.ugcc-atc-override').val();
                var hideAtc    = (hideAtcRaw === '0' || hideAtcRaw === '1') ? parseInt(hideAtcRaw, 10) : '';

                if (productId) {
                    products[productId] = {
                        id:       productId,
                        hide_atc: hideAtc,
                    };
                }
            });

            items[index] = {
                video_id:     videoId,
                video_url_hd: videoUrlHd,
                video_url_sd: videoUrlSd,
                poster_url:   posterUrl,
                products:     products,
            };
        });

        return items;
    }

    /**
     * Handle save-content button click — serializes DOM state and posts to AJAX.
     *
     * @return {void}
     */
    function onSaveContentClick() {
        var $btn       = $(this);
        var $status    = $btn.siblings('.ugcc-save-status');
        var carouselId = $('#ugcc-carousel-id').val();

        $btn.prop('disabled', true);

        $.post(ugccAdmin.ajaxurl, {
            action:      'ugcc_save_content',
            nonce:       ugccAdmin.nonce,
            carousel_id: carouselId,
            items:       ugccCollectContentItems(),
        })
        .done(function (res) {
            $status.text((res.data && res.data.message) ? res.data.message : 'Saved!')
                   .css('color', 'green');
            if (res.data && res.data.shortcode) {
                $('#ugcc-shortcode').text(res.data.shortcode);
            }
        })
        .fail(function () {
            $status.text('Error saving.').css('color', 'red');
        })
        .always(function () {
            $btn.prop('disabled', false);
            setTimeout(function () { $status.text(''); }, 3000);
        });
    }
    $('#ugcc-save-content').on('click', onSaveContentClick);

    /**
     * Escape a plain string for safe insertion into HTML text nodes.
     *
     * @param {string} str - Raw string that may contain HTML characters.
     * @return {string} HTML-escaped string.
     */
    function ugccEscHtml( str ) {
        return $('<div>').text(String(str)).html();
    }

    /**
     * Escape a value for safe use as an HTML attribute value.
     *
     * @param {*} val - Value to escape.
     * @return {string} Escaped attribute value.
     */
    function ugccEscAttr( val ) {
        return String(val == null ? '' : val)
            .replace(/&/g, '&amp;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#39;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;');
    }

    /**
     * Format a variation attributes object into a readable string.
     *
     * @param {Object} attrs - Key/value map of attribute name → value.
     * @return {string} Human-readable string, e.g. "Color: Red, Size: M".
     */
    function ugccFormatVariation( attrs ) {
        if ( !attrs || typeof attrs !== 'object' ) { return ''; }
        return Object.keys(attrs).map(function (k) {
            return ugccEscHtml(k) + ': ' + ugccEscHtml(attrs[k]);
        }).join(', ');
    }

    /**
     * Build a catalog-visibility badge HTML string.
     *
     * @param {string} vis - WooCommerce catalog_visibility value.
     * @return {string} Badge HTML, or empty string for 'visible'.
     */
    function ugccVisibilityBadge( vis ) {
        if ( vis === 'hidden' ) {
            return '<span class="ugcc-badge ugcc-badge--warn">⚠ Hidden from catalog</span>';
        }
        if ( vis === 'catalog' ) {
            return '<span class="ugcc-badge ugcc-badge--info">Catalog only</span>';
        }
        if ( vis === 'search' ) {
            return '<span class="ugcc-badge ugcc-badge--info">Search only</span>';
        }
        return '';
    }

    /**
     * Build a product status badge HTML string.
     *
     * @param {string} status - WordPress post status value.
     * @return {string} Badge HTML, or empty string for 'publish'.
     */
    function ugccStatusBadge( status ) {
        if ( status && status !== 'publish' ) {
            var label = status.charAt(0).toUpperCase() + status.slice(1);
            return '<span class="ugcc-badge ugcc-badge--draft">' + ugccEscHtml(label) + '</span>';
        }
        return '';
    }

    /** Parsed rows stored so the confirm handler can access them. */
    var ugccModalRows = [];

    /**
     * Build and display the import verification modal from parsed row data.
     *
     * @param {Array} rows - Row data returned by ugcc_parse_csv.
     * @return {void}
     */
    function ugccShowImportModal( rows ) {
        ugccModalRows = rows;
        var html = '';

        rows.forEach(function ( row, rowIndex ) {
            html += '<div class="ugcc-modal-row">';
            html += '<h3>' + ugccEscHtml('Row ' + ( rowIndex + 1 )) + '</h3>';

            if ( row.video_url_hd ) {
                html += '<p class="ugcc-modal-video"><strong>HD:</strong> ' + ugccEscHtml(row.video_url_hd) + '</p>';
            }

            if ( !row.products || !row.products.length ) {
                html += '<p><em>No products in this row.</em></p>';
            }

            (row.products || []).forEach(function ( productEntry, pIndex ) {
                var exp = productEntry.exported;

                html += '<div class="ugcc-modal-product">';

                // Exported-as summary for cross-environment reference.
                var exportedLabel = ugccEscHtml( exp.name || exp.sku );
                if ( exp.variation ) {
                    exportedLabel += ' <em>(' + ugccFormatVariation(exp.variation) + ')</em>';
                }
                html += '<p class="ugcc-modal-exported"><em>Exported as: ' + exportedLabel + '</em></p>';

                if ( productEntry.missing ) {
                    html += '<p class="ugcc-modal-missing">⚠ No matching product found on this site.</p>';
                } else {
                    productEntry.matches.forEach(function ( match, mIndex ) {
                        var cbId    = 'ugcc-prod-' + rowIndex + '-' + pIndex + '-m' + mIndex;
                        var badge   = ugccVisibilityBadge(match.catalog_visibility) + ugccStatusBadge(match.status);
                        // Pre-check only when there is exactly one unambiguous match.
                        var checked = ( productEntry.matches.length === 1 ) ? 'checked' : '';

                        var matchLabel = ugccEscHtml(match.name);
                        if ( match.variation_attributes ) {
                            matchLabel += ' <em>(' + ugccFormatVariation(match.variation_attributes) + ')</em>';
                        }

                        html += '<label class="ugcc-modal-match" for="' + ugccEscAttr(cbId) + '">' +
                            '<input type="checkbox"' +
                            ' id="' + ugccEscAttr(cbId) + '"' +
                            ' class="ugcc-match-cb"' +
                            ' data-row="' + rowIndex + '"' +
                            ' data-hide-atc="' + ugccEscAttr(exp.hide_atc) + '"' +
                            ' value="' + ugccEscAttr(match.id) + '"' +
                            ' ' + checked + '>' +
                            ' ' + matchLabel +
                            ' <small>SKU: ' + ugccEscHtml(match.sku) + '</small>' +
                            badge +
                            '</label>';
                    });
                }

                html += '</div>'; // .ugcc-modal-product
            });

            html += '</div>'; // .ugcc-modal-row
        });

        $('#ugcc-modal-body').html(html);
        $('#ugcc-modal-status').text('').css('color', '');
        $('#ugcc-modal-confirm').prop('disabled', false);
        $('#ugcc-import-modal').show();
    }

    /**
     * Collect confirmed product selections from the modal and post to ugcc_confirm_import.
     *
     * @return {void}
     */
    function ugccConfirmImport() {
        // Build a map of rowIndex → [{id, hide_atc}] from checked checkboxes.
        var rowMap = {};
        $('.ugcc-match-cb:checked').each(function () {
            var rowIndex = parseInt( $(this).data('row'), 10 );
            var hideAtcRaw = $(this).data('hide-atc');
            var hideAtc  = (hideAtcRaw === 0 || hideAtcRaw === '0' || hideAtcRaw === 1 || hideAtcRaw === '1')
                ? parseInt(hideAtcRaw, 10)
                : null;
            if ( !rowMap[rowIndex] ) { rowMap[rowIndex] = []; }
            rowMap[rowIndex].push({ id: parseInt(this.value, 10), hide_atc: hideAtc });
        });

        // Rebuild the full items array, injecting confirmed product selections.
        var items = ugccModalRows.map(function ( row, i ) {
            return {
                video_url_hd: row.video_url_hd,
                video_url_sd: row.video_url_sd,
                poster_url:   row.poster_url,
                products:     rowMap[i] || [],
            };
        });

        var $status = $('#ugcc-modal-status');
        $status.text('Importing…').css('color', '');
        $('#ugcc-modal-confirm').prop('disabled', true);

        $.post(ugccAdmin.ajaxurl, {
            action:      'ugcc_confirm_import',
            nonce:       ugccAdmin.nonce,
            carousel_id: $('#ugcc-carousel-id').val(),
            items:       JSON.stringify(items),
        })
        .done(function ( res ) {
            if ( res.success ) {
                $status.text( res.data.imported + ' row(s) imported.' ).css('color', 'green');
                setTimeout(function () { location.reload(); }, 1500);
            } else {
                $status.text( (res.data && res.data.message) || 'Import failed.' ).css('color', 'red');
                $('#ugcc-modal-confirm').prop('disabled', false);
            }
        })
        .fail(function () {
            $status.text('Request failed.').css('color', 'red');
            $('#ugcc-modal-confirm').prop('disabled', false);
        });
    }

    $('#ugcc-modal-confirm').on('click', ugccConfirmImport);
    $('#ugcc-modal-close, #ugcc-modal-cancel').on('click', function () {
        $('#ugcc-import-modal').hide();
        $('#ugcc-modal-status').text('');
    });

    /**
     * Handle CSV file input change — Phase 1: upload to ugcc_parse_csv and open modal.
     *
     * @return {void}
     */
    function onImportFileChange() {
        var file = this.files[0];
        if ( !file ) { return; }

        var $status = $('#ugcc-import-status');
        $status.text('Analysing…').css('color', '#888');

        var formData = new FormData();
        formData.append('action',      'ugcc_parse_csv');
        formData.append('nonce',       ugccAdmin.nonce);
        formData.append('carousel_id', $('#ugcc-carousel-id').val());
        formData.append('csv_file',    file);

        $.ajax({
            url:         ugccAdmin.ajaxurl,
            type:        'POST',
            data:        formData,
            processData: false,
            contentType: false,
        })
        .done(function ( res ) {
            if ( !res.success ) {
                $status.text( (res.data && res.data.message) || 'Parse failed.' ).css('color', 'red');
                return;
            }
            $status.text('');
            ugccShowImportModal( res.data.rows );
        })
        .fail(function () {
            $status.text('Request failed.').css('color', 'red');
        })
        .always(function () {
            // Reset so re-selecting the same file fires change again.
            $('#ugcc-import-file').val('');
        });
    }
    $('#ugcc-import-file').on('change', onImportFileChange);

    /**
     * Handle copy-shortcode button click — writes shortcode text to clipboard.
     *
     * @return {void}
     */
    function onCopyShortcodeClick() {
        var text = $('#ugcc-shortcode').text();
        if (navigator.clipboard && navigator.clipboard.writeText) {
            navigator.clipboard.writeText(text).then(function () {
                var $btn = $('#ugcc-copy-shortcode');
                $btn.text('Copied!');
                setTimeout(function () { $btn.text('Copy'); }, 2000);
            });
        } else {
            // Fallback for browsers without Clipboard API.
            var $tempClipboardInput = $('<input>').val(text).appendTo('body').select();
            document.execCommand('copy');
            $tempClipboardInput.remove();
        }
    }
    $('#ugcc-copy-shortcode').on('click', onCopyShortcodeClick);

});
