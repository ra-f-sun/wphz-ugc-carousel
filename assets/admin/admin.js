/**
 * WPHZ UGC Carousel — Admin JavaScript
 * Phase 3: Config form AJAX save
 * Phase 4: Media picker, product search, content save, drag-reorder, delete, copy
 */
/* global wphzUGC, wp */
jQuery(function ($) {

    // ── Phase 3: Config Form AJAX Save ───────────────────────────
    $('#wphz-ugc-config-form').on('submit', function (e) {
        e.preventDefault();
        var $form   = $(this);
        var $status = $form.find('.wphz-save-status');

        $.post(wphzUGC.ajaxurl, {
            action:         $form.data('action'),
            nonce:          wphzUGC.nonce,
            carousel_id:    $form.find('[name="carousel_id"]').val(),
            name:           $form.find('[name="name"]').val(),
            mute:           $form.find('[name="mute"]:checked').val(),
            direction:      $form.find('[name="direction"]:checked').val(),
        })
        .done(function (res) {
            $status.text((res.data && res.data.message) ? res.data.message : 'Saved!')
                   .css('color', 'green');
        })
        .fail(function () {
            $status.text('Error saving.').css('color', 'red');
        })
        .always(function () {
            setTimeout(function () { $status.text(''); }, 3000);
        });
    });

    // ── Phase 4: jQuery UI Sortable ──────────────────────────────
    $('#wphz-items-list').sortable({
        handle: '.wphz-drag-handle',
        axis: 'y',
        placeholder: 'wphz-sortable-placeholder',
    });

    // ── Phase 12: Add New Blank Row ───────────────────
    $('#wphz-add-blank-row').on('click', function () {
        var rowId = 'new-' + Date.now();
        var $row  = $(wphzBuildItemRow(rowId));
        $('#wphz-items-list').append($row);
    });

    // ── Phase 12: Scoped Media Picker ───────────────────
    var mediaFrame = null;
    $(document).on('click', '.wphz-media-btn', function (e) {
        e.preventDefault();
        var $btn = $(this);
        var $input = $btn.siblings('.wphz-url-input');

        if (mediaFrame) {
            mediaFrame.off('select'); // clear previous listeners
        } else {
            mediaFrame = wp.media({
                title:    wphzUGC.mediaTitle || 'Select Video',
                button:   { text: wphzUGC.mediaButton || 'Use this video' },
                library:  { type: 'video' },
                multiple: false,
            });
        }

        mediaFrame.on('select', function () {
            var attachment = mediaFrame.state().get('selection').first().toJSON();
            $input.val(attachment.url);
        });

        mediaFrame.open();
    });

    /**
     * Build HTML for a new (unsaved) item row with Dual Resolutions.
     * Uses the native HTML script template generated by content-tab.php.
     */
    function wphzBuildItemRow(rowId) {
        var tmpl = $('#tmpl-wphz-item-row').html();
        return tmpl.replace(/\{\{rowId\}\}/g, rowId);
    }

    // ── Phase 4: Product Search (debounced 300ms) ─────────────────
    var searchTimers = {};

    $(document).on('keyup', '.wphz-product-search', function () {
        var $input      = $(this);
        var rowId       = $input.data('row');
        var term        = $input.val();
        var $suggestions = $input.siblings('.wphz-product-suggestions');

        clearTimeout(searchTimers[rowId]);

        if (term.length < 2) {
            $suggestions.hide().empty();
            return;
        }

        searchTimers[rowId] = setTimeout(function () {
            $.get(wphzUGC.ajaxurl, {
                action: 'wphz_ugc_product_search',
                nonce:  wphzUGC.nonce,
                term:   term,
            })
            .done(function (res) {
                $suggestions.empty();
                if (!res.success || !res.data.length) {
                    $suggestions.hide();
                    return;
                }
                $.each(res.data, function (i, product) {
                    var thumb = product.thumbnail
                        ? '<img src="' + product.thumbnail + '" alt="">'
                        : '<span class="wphz-no-thumb"></span>';
                    
                    var cleanName = $('<div>').text(product.name).html();
                    var tmpl = $('#tmpl-wphz-product-suggestion').html();
                    
                    tmpl = tmpl.replace(/\{\{productId\}\}/g, product.id)
                               .replace(/\{\{productNameRaw\}\}/g, cleanName)
                               .replace(/\{\{thumbHtml\}\}/g, thumb)
                               .replace(/\{\{productNameTxt\}\}/g, cleanName)
                               .replace(/\{\{productPrice\}\}/g, product.price_html);
                               
                    $suggestions.append(tmpl);
                });
                $suggestions.show();
            });
        }, 300);
    });

    // Click outside → close suggestions
    $(document).on('click', function (e) {
        if (!$(e.target).closest('.wphz-product-search-wrap').length) {
            $('.wphz-product-suggestions').hide();
        }
    });

    // Select a product from suggestion dropdown → add chip
    $(document).on('click', '.wphz-product-suggestions li', function () {
        var $li          = $(this);
        var productId    = $li.data('id');
        var productName  = $li.data('name');
        var $wrap        = $li.closest('.wphz-product-search-wrap');
        var rowId        = $wrap.siblings('.wphz-product-search-wrap').find('.wphz-product-search').data('row') ||
                           $li.closest('.wphz-item-row').data('id');
        var $selectedList = $li.closest('.wphz-item-products').find('.wphz-selected-products');

        // Avoid duplicates
        if ($selectedList.find('[value="' + productId + '"]').length) {
            $li.closest('.wphz-product-suggestions').hide().empty();
            return;
        }

        var tmpl = $('#tmpl-wphz-product-chip').html();
        tmpl = tmpl.replace(/\{\{productId\}\}/g, productId)
                   .replace(/\{\{productName\}\}/g, productName)
                   .replace(/\{\{rowId\}\}/g, rowId);

        $selectedList.append(tmpl);

        $li.closest('.wphz-product-suggestions').hide().empty();
        $li.closest('.wphz-item-products').find('.wphz-product-search').val('');
    });

    // ── Phase 4: Remove Product Chip ─────────────────────────────
    $(document).on('click', '.wphz-remove-product', function () {
        $(this).closest('li.wphz-chip').remove();
    });

    // ── Phase 4: Delete Item Row ──────────────────────────────────
    $(document).on('click', '.wphz-delete-item', function () {
        var $btn  = $(this);
        var rowId = $btn.data('id');
        var $row  = $btn.closest('.wphz-item-row');

        // If it is a persisted DB row (numeric id), call the AJAX delete endpoint
        if (!isNaN(parseInt(rowId, 10))) {
            $.post(wphzUGC.ajaxurl, {
                action: 'wphz_ugc_delete_item',
                nonce:  wphzUGC.nonce,
                id:     rowId,
            })
            .always(function () {
                $row.fadeOut(200, function () { $(this).remove(); });
            });
        } else {
            // Newly-added row not yet in DB — just remove from DOM
            $row.fadeOut(200, function () { $(this).remove(); });
        }
    });

    // ── Phase 4: Save Content ─────────────────────────────────────
    $('#wphz-save-content').on('click', function () {
        var $btn       = $(this);
        var $status    = $btn.siblings('.wphz-save-status');
        var carouselId = $('#wphz-carousel-id').val();
        var items      = {};

        $('#wphz-items-list .wphz-item-row').each(function (index) {
            var $row       = $(this);
            var rowId      = $row.data('id');
            var videoId    = $row.find('[name="items[' + rowId + '][video_id]"]').val() || 0;
            var videoUrlHd = $row.find('[name="items[' + rowId + '][video_url_hd]"]').val();
            var videoUrlSd = $row.find('[name="items[' + rowId + '][video_url_sd]"]').val();
            var products = {};

            $row.find('.wphz-chip').each(function () {
                var $chip   = $(this);
                var pId     = $chip.find('input[type="hidden"][name$="[id]"]').val();
                var hideAtc = $chip.find('input[type="checkbox"][name$="[hide_atc]"]').is(':checked') ? 1 : 0;
                
                if (pId) {
                    products[pId] = {
                        id: pId,
                        hide_atc: hideAtc
                    };
                }
            });

            items[index] = {
                video_id:     videoId,
                video_url_hd: videoUrlHd,
                video_url_sd: videoUrlSd,
                products:     products,
            };
        });

        $btn.prop('disabled', true);

        $.post(wphzUGC.ajaxurl, {
            action:      'wphz_ugc_save_content',
            nonce:       wphzUGC.nonce,
            carousel_id: carouselId,
            items:       items,
        })
        .done(function (res) {
            $status.text((res.data && res.data.message) ? res.data.message : 'Saved!')
                   .css('color', 'green');
            // Refresh shortcode if returned
            if (res.data && res.data.shortcode) {
                $('#wphz-shortcode').text(res.data.shortcode);
            }
        })
        .fail(function () {
            $status.text('Error saving.').css('color', 'red');
        })
        .always(function () {
            $btn.prop('disabled', false);
            setTimeout(function () { $status.text(''); }, 3000);
        });
    });

    // ── Phase 4: Copy Shortcode to Clipboard ─────────────────────
    $('#wphz-copy-shortcode').on('click', function () {
        var text = $('#wphz-shortcode').text();
        if (navigator.clipboard && navigator.clipboard.writeText) {
            navigator.clipboard.writeText(text).then(function () {
                var $btn = $('#wphz-copy-shortcode');
                $btn.text('Copied!');
                setTimeout(function () { $btn.text('Copy'); }, 2000);
            });
        } else {
            // Fallback
            var $temp = $('<input>').val(text).appendTo('body').select();
            document.execCommand('copy');
            $temp.remove();
        }
    });

});
